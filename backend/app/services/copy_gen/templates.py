def get_template(template_id: str) -> Optional[Dict]:
    return TEMPLATES.get(template_id)


def get_all_templates() -> Dict[str, Dict]:
    return TEMPLATES


def get_platform_tone(platform: str) -> Dict:
    return PLATFORM_TONES.get(platform, PLATFORM_TONES["抖音"])


def get_industry_keywords(industry: str) -> List[str]:
    return INDUSTRY_KEYWORDS.get(industry, [])


def get_script_type(script_type: str) -> Optional[Dict]:
    return SCRIPT_TYPES.get(script_type)


def get_all_script_types() -> Dict[str, Dict]:
    return SCRIPT_TYPES


def get_all_emotions() -> List[str]:
    return EMOTION_TYPES


def get_emotion_description(emotion: str) -> str:
    return EMOTION_DESCRIPTIONS.get(emotion, "")


def get_all_platforms() -> List[str]:
    return list(PLATFORM_TONES.keys())


